/* 展开成按学习顺序排列的字（会写字在前，本课会认字跟随；按课推进） */
function flatCharList() {
  const out = [];
  YI_NIANJI.forEach(u => u.lessons.forEach(l => {
    l.write.forEach(c => out.push({ char: c, unit: u.unit, lesson: l.lesson, type: 'write', semester: u.semester }));
    l.read.forEach(c => out.push({ char: c, unit: u.unit, lesson: l.lesson, type: 'read', semester: u.semester }));
  }));
  return out;
}
const FLAT_CHARS = flatCharList();
/* 统计 */
function hanziTableStats() {
  const chars = new Set();
  FLAT_CHARS.forEach(f => chars.add(f.char));
  return { total: chars.size, lessons: FLAT_CHARS.length };
}
